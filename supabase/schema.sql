alter table public.listings enable row level security;

drop policy if exists "public read published" on public.listings;
create policy "public read published"
  on public.listings for select
  using (is_published = true);

drop policy if exists "admin read all" on public.listings;
create policy "admin read all"
  on public.listings for select
  to authenticated
  using (true);

drop policy if exists "admin write" on public.listings;
create policy "admin write"
  on public.listings for all
  to authenticated
  using (true) with check (true);

create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_listings_updated on public.listings;
create trigger trg_listings_updated
  before update on public.listings
  for each row execute function public.set_updated_at();

